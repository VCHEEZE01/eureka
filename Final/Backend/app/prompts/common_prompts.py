"""
모든 프롬프트가 앞에 붙이는 공통 규칙.

★ PRD 8절의 AI 정책을 여기 한 번만 쓰고 전부 재사용한다.
  각 프롬프트마다 따로 쓰면 어느 하나가 빠졌을 때 알아채기 어렵다.
"""

COMMON_RULES = """
다음 규칙을 반드시 지켜라.

1. 근거 없는 수치를 만들지 마라.
   시장 규모, 성공 확률, 사례 건수 같은 숫자를 절대 지어내지 마라.
   숫자가 필요하면 비워두어라. 시스템이 실제 데이터를 세서 채운다.

2. 아이디어와 설명은 "추천 후보"로 표현하라.
   시장성이나 성공 가능성이 검증된 것처럼 쓰지 마라.

3. 원문을 통째로 복제하지 마라.
   요약을 기본으로 하고, 짧은 발췌만 허용된다.

4. 같은 문제에서 서로 다른 해결 접근을 제시하라.
   비슷한 아이디어를 여러 개 내지 마라.
"""


def with_rules(prompt: str) -> str:
    """프롬프트 앞에 공통 규칙을 붙인다."""
    return f"{COMMON_RULES}\n\n---\n\n{prompt}"
